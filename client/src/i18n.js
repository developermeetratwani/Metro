export const translate = (lang) => (key, vars) => {
  let k = key, v = vars;
  const m = !D[k] && /^(err\.\w+):(.*)$/.exec(k); // "err.http:503" carries the status
  if (m) { k = m[1]; v = { s: m[2] }; }
  const s = D[k]?.[IDX[lang] ?? 0] ?? D[k]?.[0] ?? key; // unknown keys (e.g. server error text) pass through
  return v ? s.replace(/\{(\w+)\}/g, (_, n) => v[n] ?? "") : s;
};

// Translate an API-supplied value (band label, alert, level) when known, else show it as returned.
export const tv = (t, prefix, raw) => { const s = t(prefix + raw); return s === prefix + raw ? raw : s; };

export const LangContext = createContext(translate("en"));
export const useT = () => useContext(LangContext);
